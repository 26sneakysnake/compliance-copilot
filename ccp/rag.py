"""The compliance copilot: retrieve, gate, generate, validate citations, or refuse.

Guardrails, in order:
1. input guard     - empty, oversized or instruction-override questions are refused;
2. retrieval gate  - no passage scores high enough, or too few query terms are found:
                     refuse rather than let the model answer from memory;
3. generation      - extractive (offline, deterministic) or an LLM with a versioned prompt
                     that must answer only from the passages or say INSUFFICIENT_CONTEXT;
4. citation check  - every kept sentence must cite a passage that was actually retrieved;
                     invented ids are stripped, uncited sentences are dropped, and an answer
                     with no valid citation left is refused.
Every call is traced (latency, tokens, cost, prompt version) and written to the audit log.
"""
from __future__ import annotations

import re
from dataclasses import asdict, dataclass, field

import yaml

from . import config
from .audit import AuditLog
from .corpus import Chunk, load_corpus
from .llm import Completion, cost_usd
from .prompts import Prompt
from .prompts import load as load_prompt
from .retrieval import BM25Retriever, Hit, analyze
from .tracing import Tracer

CITATION_RE = re.compile(r"\[([A-Z][A-Z_]+-[a-z0-9]+(?:-[a-z0-9]+)*)\]")
INSUFFICIENT = "INSUFFICIENT_CONTEXT"
DISCLAIMER = (
    "Generated by an AI system from the cited passages. Not legal advice: check the official text "
    "and your compliance function before acting."
)
_INJECTION = re.compile(
    r"ignore (all |any |the )?(previous|prior|above) (instructions|rules)|system prompt|"
    r"disregard (your|the) (rules|instructions)|you are now|jailbreak",
    re.I,
)


@dataclass
class Citation:
    chunk_id: str
    label: str
    title: str
    source_url: str
    text_type: str


@dataclass
class Answer:
    question: str
    status: str  # "answered" | "refused"
    answer: str
    citations: list[Citation] = field(default_factory=list)
    refusal_reason: str | None = None
    retrieved: list[dict] = field(default_factory=list)
    dropped_sentences: int = 0
    invalid_citations: list[str] = field(default_factory=list)
    prompt_ref: str = ""
    model: str = ""
    input_tokens: int = 0
    output_tokens: int = 0
    cost_usd: float = 0.0
    latency_ms: float = 0.0
    trace_id: str = ""
    disclaimer: str = DISCLAIMER

    def to_dict(self) -> dict:
        return asdict(self)


def load_settings() -> dict:
    return yaml.safe_load((config.ROOT / "config" / "rag.yaml").read_text())


def split_sentences(text: str) -> list[str]:
    # split after ., ! or ? (optionally followed by citations) when a capital letter follows
    parts = re.split(r"(?<=[.!?])\s+(?=[A-Z])|(?<=\])\s+(?=[A-Z])", text.strip())
    return [p.strip() for p in parts if p.strip()]


def validate_citations(text: str, allowed: set[str]) -> tuple[list[str], list[str], int]:
    """Return (kept sentences, invalid ids, number of dropped sentences)."""
    kept, invalid, dropped = [], [], 0
    for sent in split_sentences(text):
        ids = CITATION_RE.findall(sent)
        bad = [i for i in ids if i not in allowed]
        invalid += bad
        for b in bad:
            sent = sent.replace(f"[{b}]", "").replace("  ", " ")
        if any(i in allowed for i in ids):
            kept.append(sent.strip())
        else:
            dropped += 1
    return kept, invalid, dropped


class ExtractiveGenerator:
    """Offline generator: quotes the most relevant sentence of the best passages.

    It cannot hallucinate beyond the corpus, which makes it a useful floor for
    the evaluation and a free mode for the demo deployment.
    """

    model = "extractive"

    def __init__(self, max_passages: int = 2, relative_cutoff: float = 0.6, weight=None):
        self.max_passages = max_passages
        self.relative_cutoff = relative_cutoff
        self.weight = weight or (lambda term: 1.0)  # idf from the retriever when available

    def generate(self, question: str, hits: list[Hit]) -> Completion:
        q = set(analyze(question, expand=True))
        top = hits[0].score
        sentences = []
        for h in hits[: self.max_passages]:
            if h.score < self.relative_cutoff * top:
                break
            cands = split_sentences(h.chunk.text)
            best = max(cands, key=lambda s: (sum(self.weight(t) for t in q & set(analyze(s))), -cands.index(s)))
            sentences.append(f"{h.chunk.label} ({h.chunk.title}): {best.rstrip('.')}. [{h.chunk.chunk_id}]")
        return Completion(" ".join(sentences), self.model)


class LLMGenerator:
    def __init__(self, client, prompt: Prompt):
        self.client = client
        self.prompt = prompt
        self.model = getattr(client, "model", "unknown")

    def generate(self, question: str, hits: list[Hit]) -> Completion:
        context = "\n\n".join(f"[{h.chunk.chunk_id}] {h.chunk.label} - {h.chunk.title}\n{h.chunk.text}" for h in hits)
        return self.client.complete(self.prompt.system, self.prompt.render(context=context, question=question))


class Copilot:
    def __init__(self, chunks: list[Chunk] | None = None, generator=None, prompt: Prompt | None = None,
                 tracer: Tracer | None = None, audit: AuditLog | None = None, settings: dict | None = None):
        self.chunks = chunks if chunks is not None else load_corpus()
        self.retriever = BM25Retriever(self.chunks)
        self.prompt = prompt or load_prompt("compliance_answer")
        self.generator = generator or ExtractiveGenerator(weight=self.retriever.term_weight)
        self.tracer = tracer or Tracer(enabled=False)
        self.audit = audit
        s = settings or load_settings()
        self.k = s["top_k"]
        self.min_score = s["min_top_score"]
        self.min_coverage = s["min_query_coverage"]
        self.max_question_chars = s["max_question_chars"]

    def _refuse(self, ans: Answer, reason: str) -> Answer:
        ans.status, ans.refusal_reason = "refused", reason
        ans.answer = {
            "no_source": "I cannot answer: no passage in the indexed regulations supports an answer to this question.",
            "no_valid_citation": "I cannot answer: the draft answer could not be tied to any retrieved passage.",
            "model_insufficient_context": "I cannot answer: the retrieved passages do not contain the answer.",
            "input_rejected": "I cannot process this request: it is empty, too long or tries to override the rules.",
        }[reason]
        ans.citations = []
        return ans

    def ask(self, question: str, user: str = "anonymous", role: str = "analyst") -> Answer:
        ans = Answer(question=question, status="answered", answer="", prompt_ref=self.prompt.ref,
                     model=getattr(self.generator, "model", "unknown"))
        with self.tracer.trace("ask", prompt_ref=self.prompt.ref, prompt_sha=self.prompt.sha256) as tr:
            ans.trace_id = tr.trace_id
            q = (question or "").strip()
            if not q or len(q) > self.max_question_chars or _INJECTION.search(q):
                self._refuse(ans, "input_rejected")
            else:
                with tr.span("retrieve", k=self.k) as sp:
                    hits = self.retriever.search(q, k=self.k)
                    coverage = self.retriever.query_coverage(q, hits)
                    top = hits[0].score if hits else 0.0
                    sp.set(top_score=top, coverage=round(coverage, 3), hits=[h.chunk.chunk_id for h in hits])
                ans.retrieved = [{"chunk_id": h.chunk.chunk_id, "score": h.score} for h in hits]
                if top < self.min_score or coverage < self.min_coverage:
                    self._refuse(ans, "no_source")
                else:
                    with tr.span("generate", **{"gen_ai.request.model": ans.model}) as sp:
                        comp = self.generator.generate(q, hits)
                        ans.input_tokens, ans.output_tokens = comp.input_tokens, comp.output_tokens
                        ans.cost_usd = cost_usd(comp.model, comp.input_tokens, comp.output_tokens)
                        sp.set(**{"gen_ai.usage.input_tokens": comp.input_tokens,
                                  "gen_ai.usage.output_tokens": comp.output_tokens})
                    with tr.span("validate_citations") as sp:
                        if comp.text.strip().startswith(INSUFFICIENT):
                            self._refuse(ans, "model_insufficient_context")
                        else:
                            allowed = {h.chunk.chunk_id for h in hits}
                            kept, invalid, dropped = validate_citations(comp.text, allowed)
                            ans.invalid_citations, ans.dropped_sentences = invalid, dropped
                            sp.set(invalid=len(invalid), dropped=dropped, kept=len(kept))
                            if not kept:
                                self._refuse(ans, "no_valid_citation")
                            else:
                                ans.answer = " ".join(kept)
                                cited = list(dict.fromkeys(i for s in kept for i in CITATION_RE.findall(s)))
                                index = {h.chunk.chunk_id: h.chunk for h in hits}
                                ans.citations = [Citation(c, index[c].label, index[c].title, index[c].source_url,
                                                          index[c].text_type) for c in cited if c in index]
            tr.set(status=ans.status, refusal_reason=ans.refusal_reason, cost_usd=ans.cost_usd,
                   **{"gen_ai.request.model": ans.model, "gen_ai.usage.input_tokens": ans.input_tokens,
                      "gen_ai.usage.output_tokens": ans.output_tokens})
        ans.latency_ms = tr.root.duration_ms
        if self.audit:
            self.audit.record("ask", user=user, role=role, trace_id=ans.trace_id, question=question[:500],
                              status=ans.status, refusal_reason=ans.refusal_reason,
                              citations=[c.chunk_id for c in ans.citations], prompt_ref=ans.prompt_ref,
                              model=ans.model, cost_usd=ans.cost_usd)
        return ans
